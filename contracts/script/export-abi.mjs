// Writes the ABIs the app needs from forge's build output into src/lib/chain/abi.ts.
// Run `forge build` first. No dependencies.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contractsDir = resolve(here, "..");
const outFile = resolve(contractsDir, "..", "src", "lib", "chain", "abi.ts");

function loadAbi(name) {
  const path = resolve(contractsDir, "out", `${name}.sol`, `${name}.json`);
  try {
    return JSON.parse(readFileSync(path, "utf8")).abi;
  } catch (err) {
    console.error(`Could not read ${path}. Did you run \`forge build\` in contracts/?`);
    throw err;
  }
}

const body = [
  "// Generated by contracts/script/export-abi.mjs from forge build output. Do not edit.",
  "",
  `export const awningMandateAbi = ${JSON.stringify(loadAbi("AwningMandate"), null, 2)} as const;`,
  "",
  `export const awningPoolAbi = ${JSON.stringify(loadAbi("AwningPool"), null, 2)} as const;`,
  "",
  `export const usdcAbi = ${JSON.stringify(loadAbi("MockUSDC"), null, 2)} as const;`,
  "",
].join("\n");

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);
console.log(`Wrote ${outFile}`);
